import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

// Files that write `data-lucide` placeholders. Names built at runtime appear here as string literals.
export const iconSources = ['index.html', 'app.js', 'digest.js', 'ranking.js', 'feedback.js'];

const toPascalCase = name => name.replace(/(\w)(\w*)(_|-|\s*)/g, (_, first, rest) => first.toUpperCase() + rest.toLowerCase());

// The full Lucide UMD is about 600 KB; the pages use a few dozen icons.
export async function buildIconBundle(root) {
  const lucide = path.join(root, 'node_modules/lucide/dist/esm');
  const files = new Map();
  for (const [, names, file] of (await readFile(path.join(lucide, 'lucide.js'), 'utf8')).matchAll(/export \{ ([^}]+) \} from '\.\/icons\/([a-z0-9-]+)\.js';/g)) {
    for (const name of names.split(',')) files.set(name.trim().replace(/^default as /, ''), file);
  }
  const used = new Map();
  for (const source of iconSources) {
    const text = await readFile(path.join(root, source), 'utf8');
    for (const [, name] of text.matchAll(/data-lucide="([^"$]+)"/g)) {
      if (!files.has(toPascalCase(name))) throw new Error(`Unknown Lucide icon "${name}" in ${source}`);
    }
    for (const [, name] of text.matchAll(/['"`]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"`]/g)) {
      const file = files.get(toPascalCase(name));
      if (file) used.set(name, file);
    }
  }
  const icons = {};
  for (const [name, file] of [...used].sort(([a], [b]) => a.localeCompare(b))) {
    icons[name] = (await import(pathToFileURL(path.join(lucide, 'icons', `${file}.js`)).href)).default[2];
  }
  const { default: defaults } = await import(pathToFileURL(path.join(lucide, 'defaultAttributes.js')).href);
  const { version } = JSON.parse(await readFile(path.join(root, 'node_modules/lucide/package.json'), 'utf8'));
  return `/* Lucide v${version} (ISC license), only the icons these pages use. Generated by build.mjs. */
(() => {
  const defaults = ${JSON.stringify(defaults)};
  const icons = ${JSON.stringify(icons)};
  const create = (tag, attrs, children = []) => {
    const element = document.createElementNS('http://www.w3.org/2000/svg', tag);
    for (const [name, value] of Object.entries(attrs)) element.setAttribute(name, String(value));
    for (const [childTag, childAttrs, grandchildren] of children) element.appendChild(create(childTag, childAttrs, grandchildren));
    return element;
  };
  // Same replacement rules as Lucide's createIcons: element attributes win and classes merge.
  function createIcons({ nameAttr = 'data-lucide', attrs = {} } = {}) {
    for (const element of document.querySelectorAll('[' + nameAttr + ']')) {
      const name = element.getAttribute(nameAttr);
      if (!icons[name]) { console.warn(element.outerHTML + ' icon name was not found in the provided icons object.'); continue; }
      const own = Object.fromEntries([...element.attributes].map(attribute => [attribute.name, attribute.value]));
      const classes = ['lucide', 'lucide-' + name, ...String(own.class || '').split(' '), ...String(attrs.class || '').split(' ')]
        .map(value => value.trim()).filter((value, index, all) => value && all.indexOf(value) === index);
      element.parentNode?.replaceChild(create('svg', { ...defaults, 'data-lucide': name, ...attrs, ...own, class: classes.join(' ') }, icons[name]), element);
    }
  }
  window.lucide = { createIcons, icons };
})();
`;
}
